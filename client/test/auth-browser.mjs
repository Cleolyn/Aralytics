import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { Browser, sleep } from '../../.agents/skills/design-taste-frontend/scripts/lib/cdp.mjs';
const out = '.taste-skill/auth-flow-qa'; mkdirSync(out, { recursive: true });
const browser = await Browser.launch();
try {
  const page = await browser.newPage();
  const base = 'http://127.0.0.1:3013';
  const wait = async expression => {
    for (let i = 0; i < 100; i++) { if (await page.eval(expression)) return; await sleep(100); }
    throw new Error('Timed out: ' + expression + '\n' + await page.eval(() => document.body.innerText.slice(0, 1200)));
  };
  const click = async label => { await page.eval(text => {
    const button = [...document.querySelectorAll('button')].find(b => b.textContent.includes(text));
    if (!button || button.disabled) throw new Error('Button unavailable: ' + text); button.click();
  }, label); };
  const fill = async (selector, text) => { await page.eval(sel => document.querySelector(sel).focus(), selector); await page.send('Input.insertText', { text }); };
  await page.goto(base + '/register');
  await wait("document.querySelector('.google-auth button:not(:disabled)') !== null");
  assert.equal(await page.eval(() => window.__authProviderOptions.signUpUrl), '/register');
  assert.equal(await page.eval(() => window.__authProviderOptions.signInUrl), '/login');
  assert.equal(await page.eval(() => window.__authProviderOptions.prefetchUI), true);
  await page.eval(() => { window.__ssoFailure = 'protect_check_script_load_failed'; });
  await click('Continue with Google');
  await wait("document.body.innerText.includes('Security verification could not load')");
  assert.equal(await page.eval(() => document.querySelector('.google-auth button').disabled), false);
  await page.eval(() => { window.__ssoFailure = null; }); await click('Continue with Google');
  await wait("location.pathname === '/sso-callback' && document.querySelector('[data-testid=sso-handler]') !== null");
  const sso = await page.eval(() => window.__authCalls.find(call => call.method === 'sso').params);
  assert.deepEqual(sso, { strategy: 'oauth_google', redirectUrl: '/onboarding', redirectCallbackUrl: '/sso-callback' });
  await page.screenshot({ path: `${out}/google-protect-callback.jpg` });
  await click('Complete simulated verification');
  await wait("location.pathname === '/onboarding' && document.querySelector('#class-code') !== null");
  assert.equal(await page.eval(() => document.querySelector('#student-lrn') !== null), false);
  await fill('#class-code', 'ABCDEFGH23'); await click('Continue');
  await wait("document.querySelector('#student-lrn') !== null");
  assert.equal(await page.eval(() => document.querySelector('#student-section').value), '10-Rizal');
  await fill('#student-lrn', '999999000001'); await fill('#student-full-name', 'Test Student'); await fill('#student-mobile', '09171234567');
  await click('Request to join'); await wait("document.body.innerText.includes('Waiting for approval')");
  assert.equal(await page.eval(() => location.pathname), '/onboarding');
  await page.goto(base + '/student/dashboard'); await wait("location.pathname === '/onboarding' && document.body.innerText.includes('Waiting for approval')");
  await click('Check approval status'); await wait("document.body.innerText.includes('Status checked just now.')");
  await page.eval(() => window.__authFixture.approve()); await click('Check approval status');
  await wait("location.pathname === '/student/dashboard' && document.body.innerText.includes('Hello, Test')");
  await page.goto(base + '/student/dashboard'); await wait("document.body.innerText.includes('Hello, Test')");
  await page.eval(() => window.__authFixture.signOut()); await wait("location.pathname === '/login' && document.querySelector('.google-auth button') !== null");
  await page.goto(base + '/register'); await wait("document.querySelector('[data-testid=email-sign-up]') !== null");
  await click('Start simulated email sign-up'); await wait("location.pathname === '/register/verify-email-address'");
  assert.equal(await page.eval(() => document.querySelector('.google-auth') === null), true, 'Do not restart OAuth during email verification');
  await click('Verify simulated email'); await wait("location.pathname === '/onboarding' && document.querySelector('#class-code') !== null");
  await page.eval(() => window.__authFixture.signOut()); await wait("location.pathname === '/login' && document.querySelector('.google-auth button') !== null");
  await page.goto(base + '/sign-up/protect-check');
  await wait("location.pathname === '/register/protect-check' && document.querySelector('[data-testid=signup-challenge]') !== null");
  assert.equal(await page.eval(() => document.querySelector('.google-auth') === null), true);
  await click('Complete simulated verification'); await wait("document.querySelector('#class-code') !== null");
  await page.eval(() => window.__authFixture.task('setup-mfa'));
  await wait("location.pathname === '/auth/tasks/setup-mfa' && document.body.innerText.includes('Finish account setup')");
  await click('Complete simulated account task'); await wait("location.pathname === '/onboarding' && document.querySelector('#class-code') !== null");
  await page.eval(() => window.__authFixture.signOut()); await wait("location.pathname === '/login'");
  await page.goto(base + '/sso-callback?delaySdk=1');
  assert.equal(await page.eval(() => document.body.innerText.includes('Complete your sign-in')), true, 'SDK loading must not hide the callback');
  await page.eval(() => window.__authFixture.ready()); await wait("document.querySelector('[data-testid=sso-handler]') !== null");
  await page.eval(() => window.__callbackActions.navigateToSignUp()); await wait("location.pathname === '/register' && document.querySelector('[data-testid=email-sign-up]') !== null");
  await page.eval(() => { window.__backendDown = true; window.__authFixture.finish(); });
  await wait("document.body.innerText.includes('backend is running')");
  await page.eval(() => { window.__backendDown = false; }); await click('Continue');
  await wait("document.querySelector('#class-code') !== null");
  await page.screenshot({ path: `${out}/student-ready.jpg` });
  assert.deepEqual(page.consoleErrors, []);
  console.log('PASS: real app routes/provider/context with a simulated Clerk adapter: Google challenge/error recovery, email verification, aliases, required session tasks, backend recovery, code-gated enrollment, approval, reload, and sign-out.');
} finally { await browser.close(); }
